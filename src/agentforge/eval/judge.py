"""The entailment judge, and the machinery that licenses it.

The judge decides the fuzzy half of groundedness: given a claim and the quote
cited for it, does the quote actually support the claim? The deterministic half
-- is the quote even present in its source -- needs no model at all.

**Why validation is not optional.** An LLM judge with a prompt someone wrote is
an instrument of unknown precision, and every number computed with it inherits
that. So the judge is scored against reference labels and reported with Cohen's
kappa, and a judge below the floor is REFUSED rather than used with a footnote.

**Why kappa rather than agreement.** The label distribution is skewed: in a
working system most claims are entailed. A judge that answered "entailed" every
time would post ~90% raw agreement and have no skill whatsoever. Kappa measures
agreement above chance, and it is the number that catches that judge.

**Why the label source is carried everywhere.** Reference labels generated by a
model and labels checked by a human license completely different claims. Calling
the former "human agreement" is precisely the overstatement this project is
organised to avoid, so `label_source` travels with the figure and
`human_validated` is false until someone has actually reviewed them.
"""

from __future__ import annotations

from dataclasses import dataclass

from agentforge.agents import prompts
from agentforge.agents.verify import ENTAILMENT_SCHEMA
from agentforge.db.conn import pool
from agentforge.errors import MeasurementError
from agentforge.eval.stats import cohens_kappa
from agentforge.llm import LLMClient

HUMAN_REVIEWED = "human-reviewed"
MODEL_PENDING = "model-pending-review"


@dataclass(frozen=True)
class JudgeValidation:
    judge_model: str
    prompt_version: str
    kappa: float
    agreement: float
    n_pairs: int
    label_source: str
    usable: bool
    note: str

    @property
    def human_validated(self) -> bool:
        return self.label_source == HUMAN_REVIEWED

    def describe(self) -> str:
        qualifier = "" if self.human_validated else " (labels pending human review)"
        return (
            f"{self.judge_model} @ {self.prompt_version}: kappa={self.kappa:.3f}, "
            f"agreement={self.agreement:.3f}, n={self.n_pairs}{qualifier}"
        )


class EntailmentJudge:
    def __init__(self, llm: LLMClient, prompt_version: str = prompts.PROMPT_VERSION) -> None:
        self.llm = llm
        self.prompt_version = prompt_version

    def judge(self, claim: str, quote: str) -> str:
        """One verdict. The prompt carries a claim and a quote, nothing else."""
        response = self.llm.complete(
            prompts.JUDGE_SYSTEM,
            f"Claim:\n{claim}\n\nQuote:\n{quote}",
            ENTAILMENT_SCHEMA,
        )
        return response.parsed["verdict"]


def store_reference_pairs(
    pairs: list[tuple[str, str, str]], label_source: str, chunk_id: str = ""
) -> int:
    """Store (claim, quote, label) reference pairs. Idempotent by content."""
    import hashlib

    rows = []
    for claim, quote, label in pairs:
        pair_id = hashlib.sha256(f"{claim}\x00{quote}".encode()).hexdigest()[:16]
        rows.append((pair_id, claim, quote, chunk_id, label, label_source))

    with pool().connection() as conn, conn.cursor() as cur:
        cur.executemany(
            """
            INSERT INTO judge_reference
              (pair_id, claim_text, quote, chunk_id, label, label_source)
            VALUES (%s,%s,%s,%s,%s,%s)
            ON CONFLICT (pair_id) DO UPDATE SET
              label = EXCLUDED.label, label_source = EXCLUDED.label_source
            """,
            rows,
        )
    return len(rows)


def mark_reviewed(pair_id: str, label: str) -> None:
    """Record a human's verdict on one pair. This is what makes kappa real."""
    with pool().connection() as conn:
        conn.execute(
            "UPDATE judge_reference SET label = %s, label_source = %s, reviewed_at = now() "
            "WHERE pair_id = %s",
            (label, HUMAN_REVIEWED, pair_id),
        )


def reference_pairs() -> list[dict]:
    with pool().connection() as conn:
        return [
            dict(row)
            for row in conn.execute(
                "SELECT pair_id, claim_text, quote, label, label_source "
                "FROM judge_reference ORDER BY pair_id"
            )
        ]


def validate_judge(judge: EntailmentJudge, min_kappa: float = 0.70) -> JudgeValidation:
    """Score a judge against the stored reference labels and persist the result."""
    pairs = reference_pairs()
    if not pairs:
        raise MeasurementError(
            "no reference pairs stored: a judge cannot be validated against nothing, "
            "and an unvalidated judge makes every groundedness number decorative"
        )

    reference = [p["label"] for p in pairs]
    predicted = [judge.judge(p["claim_text"], p["quote"]) for p in pairs]

    try:
        kappa, agreement = cohens_kappa(reference, predicted)
    except ValueError as exc:
        raise MeasurementError(f"kappa is undefined for these labels: {exc}") from exc

    # If the pairs are mixed, the weaker provenance governs the claim.
    sources = {p["label_source"] for p in pairs}
    label_source = HUMAN_REVIEWED if sources == {HUMAN_REVIEWED} else MODEL_PENDING

    usable = kappa >= min_kappa
    notes: list[str] = []
    if not usable:
        notes.append(
            f"kappa {kappa:.3f} is below the {min_kappa:.2f} floor: this judge is not a "
            "usable instrument. Fix the prompt and re-measure rather than reporting "
            "numbers computed with it."
        )
    if label_source != HUMAN_REVIEWED:
        notes.append(
            "reference labels are model-drafted and pending human review, so this "
            "figure measures agreement with the drafting model, not with a human."
        )
    note = " ".join(notes) or "within tolerance against human-reviewed labels."

    result = JudgeValidation(
        judge_model=judge.llm.model,
        prompt_version=judge.prompt_version,
        kappa=kappa,
        agreement=agreement,
        n_pairs=len(pairs),
        label_source=label_source,
        usable=usable,
        note=note,
    )

    with pool().connection() as conn:
        conn.execute(
            """
            INSERT INTO judge_validation
              (judge_model, prompt_ver, n_pairs, kappa, agreement, label_source)
            VALUES (%s,%s,%s,%s,%s,%s)
            ON CONFLICT (judge_model, prompt_ver, label_source) DO UPDATE SET
              n_pairs = EXCLUDED.n_pairs, kappa = EXCLUDED.kappa,
              agreement = EXCLUDED.agreement, measured_at = now()
            """,
            (
                result.judge_model, result.prompt_version, result.n_pairs,
                result.kappa, result.agreement, result.label_source,
            ),
        )
    return result


REFERENCE_PATH = "data/judge_reference.jsonl"
_LABELS = set(ENTAILMENT_SCHEMA["properties"]["verdict"]["enum"])


def load_reference_file(path: str = REFERENCE_PATH) -> dict[str, int]:
    """Load reference pairs from the versioned JSONL, verifying every quote.

    A quote not found verbatim in its chunk would make the pair test something
    other than entailment, so it raises. Labels arrive as MODEL_PENDING (they
    were drafted by a model, Claude), and a reload never overwrites a pair a
    human has already reviewed -- that review is the one thing here that cannot
    be regenerated.
    """
    import hashlib
    import json

    from agentforge.ingest.normalize import quote_found

    with open(path, encoding="utf-8") as handle:
        rows = [json.loads(line) for line in handle if line.strip()]
    with pool().connection() as conn:
        for lineno, row in enumerate(rows, start=1):
            if set(row) != {"chunk_id", "quote", "claim", "label"}:
                raise MeasurementError(f"{path}:{lineno}: unexpected fields {sorted(row)}")
            if row["label"] not in _LABELS:
                raise MeasurementError(f"{path}:{lineno}: label {row['label']!r}")
            chunk = conn.execute(
                "SELECT text FROM chunks WHERE chunk_id = %s", (row["chunk_id"],)
            ).fetchone()
            if chunk is None or not quote_found(row["quote"], chunk["text"]):
                raise MeasurementError(f"{path}:{lineno}: quote not verbatim in {row['chunk_id']}")

        ids = [
            hashlib.sha256(f"{r['claim']}\x00{r['quote']}".encode()).hexdigest()[:16] for r in rows
        ]
        if len(set(ids)) != len(ids):
            raise MeasurementError(f"{path}: duplicate (claim, quote) pairs")
        stale = conn.execute(
            "SELECT count(*) AS n FROM judge_reference WHERE NOT (pair_id = ANY(%s))", (ids,)
        ).fetchone()["n"]
        if stale:
            raise MeasurementError(
                f"{stale} stored reference pairs are not in {path}; kappa would be computed "
                "over a set nobody can see. Remove them deliberately."
            )
        with conn.cursor() as cur:
            cur.executemany(
                """
                INSERT INTO judge_reference (pair_id, claim_text, quote, chunk_id, label, label_source)
                VALUES (%s,%s,%s,%s,%s,%s)
                ON CONFLICT (pair_id) DO UPDATE SET label = EXCLUDED.label
                WHERE judge_reference.label_source <> %s
                """,
                [
                    (pid, r["claim"], r["quote"], r["chunk_id"], r["label"], MODEL_PENDING,
                     HUMAN_REVIEWED)
                    for pid, r in zip(ids, rows, strict=True)
                ],
            )
        reviewed = conn.execute(
            "SELECT count(*) AS n FROM judge_reference WHERE label_source = %s", (HUMAN_REVIEWED,)
        ).fetchone()["n"]
    return {"pairs": len(rows), "human_reviewed": reviewed}
